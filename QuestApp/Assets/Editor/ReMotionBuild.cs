#if UNITY_EDITOR
using System.IO;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace ReMotionXR.Editor
{
    /// <summary>
    /// Quest APK build. Batchmode:
    /// Unity -batchmode -nographics -buildTarget Android -projectPath QuestApp
    ///       -executeMethod ReMotionXR.Editor.ReMotionBuild.BuildApkBatchmode
    /// Produces QuestApp/Builds/ReMotionXR.apk (development build, so the
    /// [ReMotion] pinch/camera diagnostics are visible in logcat).
    /// </summary>
    public static class ReMotionBuild
    {
        public const string ApkPath = "Builds/ReMotionXR.apk";
        private const string MainScene = "Assets/Scenes/Main.unity";

        [MenuItem("ReMotion XR/Build Quest APK")]
        /// <summary>
        /// Every APK build updates the menu version label: build number
        /// increments, bundle version follows BuildInfo.Version, and the
        /// generated BuildInfo.cs records build time + git hash.
        /// </summary>
        public static void StampBuildInfo()
        {
            int buildNumber = PlayerSettings.Android.bundleVersionCode + 1;
            PlayerSettings.bundleVersion = Core.BuildInfo.Version;
            PlayerSettings.Android.bundleVersionCode = buildNumber;
            string gitHash = "local";
            try
            {
                var startInfo = new System.Diagnostics.ProcessStartInfo("git", "rev-parse --short HEAD")
                {
                    WorkingDirectory = Application.dataPath,
                    RedirectStandardOutput = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                };
                using var process = System.Diagnostics.Process.Start(startInfo);
                string outputText = process.StandardOutput.ReadToEnd().Trim();
                process.WaitForExit(5000);
                if (!string.IsNullOrEmpty(outputText)) gitHash = outputText;
            }
            catch { /* label falls back to "local" */ }
            string stamp = System.DateTime.Now.ToString("yyyy-MM-dd HH:mm");
            string code =
                "namespace ReMotionXR.Core\n{\n" +
                "    /// <summary>Generated by ReMotionBuild.StampBuildInfo on every APK build. Do not edit by hand.</summary>\n" +
                "    public static class BuildInfo\n    {\n" +
                $"        public const string Version = \"{Core.BuildInfo.Version}\";\n" +
                $"        public const int BuildNumber = {buildNumber};\n" +
                $"        public const string Stamp = \"{stamp}\";\n" +
                $"        public const string GitHash = \"{gitHash}\";\n" +
                "        public static string Label => $\"v{Version} · build {BuildNumber} · {GitHash} · {Stamp}\";\n" +
                "    }\n}\n";
            File.WriteAllText(Path.Combine(Application.dataPath, "Scripts/Core/BuildInfo.cs"), code);
            AssetDatabase.ImportAsset("Assets/Scripts/Core/BuildInfo.cs");
            Debug.Log($"[ReMotion] BuildInfo stamped: v{Core.BuildInfo.Version} build {buildNumber} ({gitHash}, {stamp})");
        }

        private static void EnforceNormalBuildIdentity()
        {
            const string normalId = "com.remotion.xr";
            const string normalName = "ReMotion XR";
            const string normalScene = "Assets/Scenes/Main.unity";

            if (!System.IO.File.Exists(normalScene))
                throw new System.IO.FileNotFoundException("Normal Main scene is missing.", normalScene);

            UnityEditor.PlayerSettings.SetApplicationIdentifier(
                UnityEditor.BuildTargetGroup.Android, normalId);
            UnityEditor.PlayerSettings.productName = normalName;
            UnityEditor.AssetDatabase.SaveAssets();

            if (UnityEditor.PlayerSettings.GetApplicationIdentifier(
                    UnityEditor.BuildTargetGroup.Android) != normalId)
                throw new System.InvalidOperationException("Normal Android package identity was not applied.");
        }

        public static bool BuildQuestApk()
        {
            ReMotionAndroidBuildSetup.ApplyQuestBuildSettings();
            EnforceNormalBuildIdentity();
            StampBuildInfo();
            string output = Path.GetFullPath(Path.Combine(Application.dataPath, "..", ApkPath));
            Directory.CreateDirectory(Path.GetDirectoryName(output));
            if (File.Exists(output)) File.Delete(output); // never mistake a stale APK for this build

            var options = new BuildPlayerOptions
            {
                scenes = new[] { MainScene },
                locationPathName = output,
                target = BuildTarget.Android,
                targetGroup = BuildTargetGroup.Android,
                options = BuildOptions.Development,
            };
            var report = BuildPipeline.BuildPlayer(options);
            if (report.summary.result != BuildResult.Succeeded)
            {
                Debug.LogError($"[ReMotion] APK build FAILED: {report.summary.result} " +
                               $"({report.summary.totalErrors} errors)");
                return false;
            }
            Debug.Log($"[ReMotion] APK built: {output} ({report.summary.totalSize} bytes)");
            WriteBuildManifest(output);
            return true;
        }

        /// <summary>Manifest next to the APK so install tooling can verify
        /// identity (applicationId/scene0/versions/hash) from the artifact
        /// record instead of the file name. Contains no credentials.</summary>
        private static void WriteBuildManifest(string apkPath)
        {
            string sha256;
            using (var sha = System.Security.Cryptography.SHA256.Create())
            using (var stream = File.OpenRead(apkPath))
                sha256 = System.BitConverter.ToString(sha.ComputeHash(stream)).Replace("-", "");
            string applicationId = PlayerSettings.GetApplicationIdentifier(BuildTargetGroup.Android);
            string manifest =
                "{\n" +
                "  \"purpose\": \"normal ReMotion app\",\n" +
                $"  \"applicationId\": \"{applicationId}\",\n" +
                $"  \"productName\": \"{PlayerSettings.productName}\",\n" +
                $"  \"scene0\": \"{MainScene}\",\n" +
                $"  \"versionCode\": {PlayerSettings.Android.bundleVersionCode},\n" +
                $"  \"versionName\": \"{PlayerSettings.bundleVersion}\",\n" +
                $"  \"apkPath\": \"{apkPath.Replace("\\", "\\\\")}\",\n" +
                $"  \"sha256\": \"{sha256}\"\n" +
                "}\n";
            File.WriteAllText(apkPath + ".build-manifest.json", manifest);
            Debug.Log("[ReMotion] BuildManifest " + manifest.Replace("\n", " "));
        }

        /// <summary>Batchmode entry point; exits non-zero on failure.</summary>
        public static void BuildApkBatchmode() => EditorApplication.Exit(BuildQuestApk() ? 0 : 1);
    }
}
#endif
